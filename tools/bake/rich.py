#!/usr/bin/env python3
"""St Maarten: the rich man (KayKit, through kaykit.py) - a portly gentleman in a long fur coat, a top hat,
a cane with a gold knob, a moustache. He walks nose up; passing a beggar he snubs him (chin up, head
turned away); sung to he pats his pockets (nothing - or a coin after all).

    python3 tools/bake/rich.py recipes      # -> tools/bake/recipes/stmaarten/rich.json
    python3 tools/bake/rich.py bake         # -> themes/stmaarten/anim/rich

Clips: walk (nose up), snub (walking past a beggar, head turned away), idle, pat (pockets), give (a coin
held out), turn_front / turn_side.
"""
import json
import os
import subprocess
import sys

import kids

HERE = os.path.dirname(os.path.abspath(__file__))
RDIR = kids.RDIR
OUT = kids.OUT
G = kids.G

COAT, FUR, HAT, SKIN = "#5a3424", "#c9b08a", "#1e1c22", "#f0b898"
NOSE_UP = {"head": [-18, 0, 0]}
CANE = [  # in the right hand, its foot on the ground in the walk
    {"name": "cane", "bone": "handslot.r", "shape": "cube", "at": [-0.3, 0, 0], "size": [0.6, 0.05, 0.05], "color": "#1a1410"},
    {"name": "cane_knob", "bone": "handslot.r", "shape": "sphere", "at": [0, 0.02, 0], "size": [0.08, 0.08, 0.08], "color": "#e8c040"},
]


def clip(action, yaw, **kw):
    c = {"action": action, "yaw": yaw}
    c.update(kw)
    return c


def rich():
    body = "Mage"
    hide = list(kids.HIDE_ALL) + ["Mage_Head"]
    parts = [{"model": G + "Knight.glb", "meshes": ["Knight_Head"]}]
    tex = "mage_texture"
    recolor = {tex: {c: COAT for c in kids.BODY[body]["coat"]}}
    recolor[tex].update({c: FUR for c in kids.BODY[body]["trim"]})
    recolor[tex]["0,0"] = SKIN
    recolor["knight_texture"] = {"0,0": SKIN, "1,0": "#8a8078", "2,0": "#8a8078"}     # (grey hair, grey moustache)
    props = [
        # top hat: crown and brim, a band
        {"bone": "head", "shape": "cylinder", "at": [0, 0.0, 0.96], "size": [0.57, 0.68], "axis": "z", "color": HAT},
        {"bone": "head", "shape": "cylinder", "at": [0, 0.04, 0.62], "size": [0.72, 0.05], "axis": "z", "color": HAT},
        {"bone": "head", "shape": "cylinder", "at": [0, 0.04, 0.7], "size": [0.505, 0.1], "axis": "z", "color": "#6a1a22"},
        # a big grey moustache, a monocle
        {"bone": "head", "shape": "sphere", "at": [-0.12, -0.5, 0.22], "size": [0.16, 0.07, 0.06], "rot": [0, -15, 0], "color": "#8a8078"},
        {"bone": "head", "shape": "sphere", "at": [0.12, -0.5, 0.22], "size": [0.16, 0.07, 0.06], "rot": [0, 15, 0], "color": "#8a8078"},
        {"name": "monocle", "bone": "head", "shape": "cylinder", "at": [0.17, -0.5, 0.42], "size": [0.11, 0.03], "axis": "y", "color": "#dff0f6"},
        # the fur: a thick collar, cuffs, a fur hem round the coat
        {"bone": "chest", "shape": "sphere", "at": [0, 0.02, 0.26], "size": [0.56, 0.48, 0.2], "color": FUR},
        {"bone": "lowerarm.l", "shape": "cylinder", "at": [0.2, 0, 0], "size": [0.15, 0.12], "axis": "x", "color": FUR},
        {"bone": "lowerarm.r", "shape": "cylinder", "at": [-0.2, 0, 0], "size": [0.15, 0.12], "axis": "x", "color": FUR},
        {"bone": "hips", "shape": "cone", "at": [0, 0.0, 0.05], "size": [0.5, 0.64, 0.44], "color": COAT},    # (the long coat)
        {"bone": "hips", "shape": "cone", "at": [0, 0.0, -0.25], "size": [0.53, 0.08, 0.51], "color": FUR},
        {"bone": "hips", "shape": "cube", "at": [0, -0.47, 0.01], "size": [0.1, 0.04, 0.5], "rot": [-8, 0, 0], "color": FUR},
        # gloves, a gold watch chain over the belly
        {"bone": "hand.l", "shape": "sphere", "at": [0.09, 0, 0], "size": [0.12, 0.12, 0.12], "color": "#e8e0d0"},
        {"bone": "hand.r", "shape": "sphere", "at": [-0.09, 0, 0], "size": [0.12, 0.12, 0.12], "color": "#e8e0d0"},
        {"bone": "spine", "shape": "cube", "at": [0.1, -0.42, 0.12], "size": [0.26, 0.03, 0.03], "rot": [0, -20, 0], "color": "#e8c040"},
        # the coin (only in give)
        {"name": "coin", "bone": "handslot.l", "shape": "cylinder", "at": [0, 0, 0], "size": [0.09, 0.025], "axis": "y", "color": "#f0d050"},
    ] + CANE
    turned_away = {"head": [-22, 35, 0]}
    clips = {
        "walk": clip("Walking_A", 90, loop=True, stride="auto", step=3, speed=0.8, turn=NOSE_UP, drop=["coin"]),
        "snub": clip("Walking_A", 90, loop=True, stride="auto", step=3, speed=0.8, turn=turned_away, drop=["coin"]),
        "idle": clip("Idle", 20, loop=True, frames=8, step=5, turn=NOSE_UP, drop=["coin"]),
        "turn_front": clip("Idle", [90, 30], frames=4, turn=NOSE_UP, drop=["coin"]),
        "turn_side": clip("Idle", [30, 90], frames=4, turn=NOSE_UP, drop=["coin"]),
        "pat": clip("Interact", 30, step=3, drop=["coin"]),
        "give": clip("Idle", 55, frames=10, step=3, turn={"upperarm.l": [0, 0, -55]}, ramp=[0, 1]),
    }
    return {"_doc": "St Maarten, the rich man (generated by tools/bake/rich.py - edit there)",
            "model": G + body + ".glb", "parts": parts, "hide": hide, "recolor": recolor, "outline": 0.01,
            "props_rest": True,
            "bone_scale": {"upperleg.l": 1.2, "upperleg.r": 1.2, "lowerleg.l": 1.12, "lowerleg.r": 1.12,
                           "spine": [1.18, 1, 1.25], "chest": [1 / 1.18, 1, 1 / 1.25]},     # (a belly; the rest kept)
            "frame": {"x": [-1.3, 1.3], "h": 3.3}, "props": props, "clips": clips}


def write_recipes():
    os.makedirs(RDIR, exist_ok=True)
    with open(os.path.join(RDIR, "rich.json"), "w") as f:
        json.dump(rich(), f, indent=1)
    print("recipes rich")


def bake(size=320):
    env = dict(os.environ, PYTHONPATH=kids.PYLIB)
    out = os.path.join(OUT, "rich")
    p = subprocess.run(["blender", "-b", "-P", os.path.join(HERE, "kaykit.py"), "--", os.path.join(RDIR, "rich.json"),
                        out, str(size)], env=env, capture_output=True, text=True)
    ok = "BAKED" in p.stdout
    print("rich", "ok" if ok else "FAILED\n" + p.stdout[-2000:] + p.stderr[-2000:], flush=True)
    if ok:
        subprocess.run([sys.executable, os.path.join(HERE, "quantize.py"), out], capture_output=True)
    return ok


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "recipes"
    if cmd == "recipes":
        write_recipes()
    elif cmd == "bake":
        write_recipes()
        sys.exit(0 if bake() else 1)
