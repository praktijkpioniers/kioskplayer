# Write the mummified version of a character's recipe (for kaykit.py): the same model, colours and
# props, every mesh wrapped in a bandage shell (props stay bare: her crown, the witch's hat still
# show), with its walk / idle / turns wrapped and a "wrap" clip - facing the viewer, the bandage
# winding up from the feet to the head (the mummy got it: see hooks.mummify in themes/engine.lua).
#
#   python3 tools/bake/mummified.py tools/bake/recipes/princess.json   -> princess_mummified.json
#   PYTHONPATH=~/assets-src/pylib blender -b -P tools/bake/kaykit.py -- \
#       tools/bake/recipes/princess_mummified.json themes/halloween/anim/princess_mummified

import copy, json, os, sys

src = sys.argv[1]
R = json.load(open(src))
name = os.path.splitext(os.path.basename(src))[0]
M = {k: copy.deepcopy(v) for k, v in R.items() if k not in ("clips", "_doc", "shell", "heap")}
M["_doc"] = "Generated by tools/bake/mummified.py from %s.json: wrapped by the mummy." % name
M["shell"] = {"meshes": "all", "thickness": 0.04, "color": "#e8e1cc", "stripe": "#a89b80",
              "stripes": 5, "edge": 0.05}
C = R["clips"]
clips = {}
for k in ("walk", "idle", "turn_front", "turn_side"):
    c = copy.deepcopy(C[k])
    for drop in ("track", "wrap", "heap"):
        c.pop(drop, None)
    clips[k] = c
clips["walk"]["speed"] = round(clips["walk"].get("speed", 1) * 0.7, 3)     # (a mummy's shuffle)
front = C["idle"].get("yaw", 15)
clips["wrap"] = {"action": C["idle"]["action"], "yaw": front, "frames": 24, "step": 1, "wrap": [0, 1]}
M["clips"] = clips
out = os.path.join(os.path.dirname(src), name + "_mummified.json")
json.dump(M, open(out, "w"), indent=1)
print(out)
