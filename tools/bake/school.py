#!/usr/bin/env python3
"""St Maarten: the school and its teachers (the class's lantern walk).

    python3 tools/bake/school.py building          # -> themes/stmaarten/anim/school (PIL, as church.py)
    python3 tools/bake/school.py recipes           # -> tools/bake/recipes/stmaarten/{juf,meester}.json
    python3 tools/bake/school.py bake [juf meester] # -> themes/stmaarten/anim/{juf,meester} (kaykit.py)

juf, meester  grown-ups with the lantern children's clips (kids.py: walk, idle, sing, give, skip, cheer,
              turns; the left hand tracked), so the engine walks them at the head of a group like a child
              and draws the big lantern on its pole (lanterns.py pole_*) in that hand. Longer legs.
school        a Dutch primary school: a long low brick building, big windows with paper lanterns the
              children made stuck on them, a little bell turret, a board over the door; clips idle,
              open (the double door; backwards: shut), opened. origin_px = the door's middle on the step.
"""
import json, math, os, subprocess, sys
from concurrent.futures import ThreadPoolExecutor

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kids                                                              # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
RDIR = kids.RDIR
OUT = kids.OUT
G = kids.G

TEACHERS = {
    # name: body, coat, trim, skin, hat (kids.hat_props kind), wool, wool2, scarf
    "juf": ("Mage", "#2f6f7a", "#e8d8b0", "#f2c09a", "beanie", "#c0346e", "#e8e0d0", "#c0346e"),
    "meester": ("Rogue", "#6a4a32", "#d8c8a0", "#d9a074", "cap", "#5a5e66", "#5a5e66", "#2f9a52"),
}


def teacher(name):
    body, coat, trim, skin, hat, wool, wool2, scarf = TEACHERS[name]
    hide = list(kids.HIDE_ALL)
    parts = []
    face_tex = f"{body.lower()}_texture"
    if name == "meester":
        parts = [{"model": G + "Knight.glb", "meshes": ["Knight_Head"]}]
        hide.append("Rogue_Head")
        face_tex = "knight_texture"
    tex = f"{body.lower()}_texture"
    recolor = {tex: {c: coat for c in kids.BODY[body]["coat"]}}
    recolor[tex].update({c: trim for c in kids.BODY[body]["trim"][:1]})
    recolor[tex]["0,0"] = skin
    recolor.setdefault(face_tex, {})["0,0"] = skin
    if name == "meester":
        recolor[face_tex].update({"1,0": "#4a3a30", "2,0": "#4a3a30"})       # (hair, a moustache-brown)
    props = kids.hat_props(hat, wool, wool2) + kids.scarf_props(scarf)
    props += [{"bone": "hand.l", "shape": "sphere", "at": [0.09, 0, 0], "size": [0.12, 0.12, 0.12], "color": "#3a3030"},
              {"bone": "hand.r", "shape": "sphere", "at": [-0.09, 0, 0], "size": [0.12, 0.12, 0.12], "color": "#3a3030"}]
    if name == "meester":    # round glasses and a moustache
        props += [{"bone": "head", "shape": "cylinder", "at": [x, -0.5, 0.42], "size": [0.1, 0.03], "axis": "y", "color": "#cfe0e8"}
                  for x in (-0.16, 0.16)]
        props += [{"bone": "head", "shape": "cube", "at": [0, -0.5, 0.22], "size": [0.26, 0.06, 0.06], "color": "#4a3a30"}]
    return {"_doc": f"St Maarten teacher '{name}' (generated by tools/bake/school.py - edit there)",
            "model": G + body + ".glb", "parts": parts, "hide": hide, "recolor": recolor, "outline": 0.01,
            "props_rest": True, "bone_scale": {"upperleg.l": 1.25, "upperleg.r": 1.25, "lowerleg.l": 1.15, "lowerleg.r": 1.15},
            "frame": {"x": [-1.2, 1.2], "h": 3.1}, "props": props, "clips": kids.CLIPS}


def write_recipes():
    os.makedirs(RDIR, exist_ok=True)
    for n in TEACHERS:
        with open(os.path.join(RDIR, n + ".json"), "w") as f:
            json.dump(teacher(n), f, indent=1)
    print("recipes", list(TEACHERS))


def bake(names, jobs=2, size=320):
    env = dict(os.environ, PYTHONPATH=kids.PYLIB)

    def one(n):
        out = os.path.join(OUT, n)
        p = subprocess.run(["blender", "-b", "-P", os.path.join(HERE, "kaykit.py"), "--", os.path.join(RDIR, n + ".json"),
                            out, str(size)], env=env, capture_output=True, text=True)
        ok = "BAKED" in p.stdout
        print(n, "ok" if ok else "FAILED\n" + p.stdout[-2000:] + p.stderr[-2000:], flush=True)
        if ok:
            subprocess.run([sys.executable, os.path.join(HERE, "quantize.py"), out], capture_output=True)
        return ok

    with ThreadPoolExecutor(jobs) as ex:
        return all(ex.map(one, names))


# ── the building ─────────────────────────────────────────────────────────────

def building():
    from stm_scenery import Canvas, INK, rgb, mix, dark, write_anim
    W_, H_ = 560, 520
    GROUND = 512
    DX = 280
    DOOR = (240, 320, 362, 500)
    BRICK, MORTAR, TRIM = rgb("#a0533a"), rgb("#7a3c2a"), rgb("#f0ebe0")
    ROOF, ROOF_D = rgb("#3e4452"), rgb("#2c313c")
    GLASS, WARM = rgb("#f2c46a"), rgb("#ffe39a")
    LANT = [rgb(h) for h in ("#ff8c1e", "#eb322d", "#ffd732", "#4682f0", "#46c85a", "#fa6eb4", "#a05ae6")]
    UNIT_PX = 166 / 2.4

    def frame(door=0.0, flick=0.0):
        c = Canvas(W_, H_)
        # roof (a long hip roof) and the bell turret
        c.poly([(18, 236), (80, 150), (W_ - 80, 150), (W_ - 18, 236)], ROOF)
        for y in (172, 194, 216):
            f = (y - 150) / 86
            c.line([(80 - 62 * f, y), (W_ - 80 + 62 * f, y)], ROOF_D, 1.2)
        c.rect(DX - 26, 92, DX + 26, 152, TRIM)
        c.poly([(DX - 34, 96), (DX, 52), (DX + 34, 96)], ROOF)
        c.rect(DX - 14, 104, DX + 14, 140, rgb("#2a2430"))
        c.poly([(DX - 7, 112), (DX + 7, 112), (DX + 10, 132), (DX - 10, 132)], rgb("#c08a3a"))
        c.line([(DX, 52), (DX, 38)], INK, 2.5)
        c.poly([(DX, 38), (DX + 16, 43), (DX, 48)], rgb("#e8b828"), INK, 1.2)     # a little weather vane flag
        # walls
        c.rect(30, 232, W_ - 30, GROUND, BRICK)
        y, k = 244, 0
        while y < GROUND:
            c.line([(32, y), (W_ - 32, y)], MORTAR, 1.0)
            x = 34 + (12 if k % 2 else 0)
            while x < W_ - 34:
                c.line([(x, y - 12), (x, y)], MORTAR, 0.8)
                x += 24
            y, k = y + 12, k + 1
        c.rect(26, 228, W_ - 26, 240, TRIM)
        # big windows (two either side), the children's lanterns stuck on them
        k = 0
        for x0 in (50, 140, 340, 430):
            c.rect(x0 - 6, 276, x0 + 86, 420, TRIM)
            c.rect(x0, 282, x0 + 80, 414, mix(GLASS, 0.1 * flick))
            c.line([(x0 + 40, 282), (x0 + 40, 414)], TRIM, 3)
            c.line([(x0, 340), (x0 + 80, 340)], TRIM, 3)
            for j, (lx, ly) in enumerate(((x0 + 18, 300), (x0 + 60, 318), (x0 + 22, 368), (x0 + 62, 386))):
                col = LANT[(k + j) % len(LANT)]
                if j % 2:
                    pts = [(lx + 12 * math.cos(-math.pi / 2 + i * math.pi / 5) * (1 if i % 2 == 0 else 0.5),
                            ly + 12 * math.sin(-math.pi / 2 + i * math.pi / 5) * (1 if i % 2 == 0 else 0.5)) for i in range(10)]
                    c.poly(pts, col, INK, 1.2)
                else:
                    c.ell(lx, ly, 10, 12, col, INK, 1.2)
            k += 2
            c.rect(x0 - 8, 420, x0 + 88, 428, TRIM)
        # the board over the door: SCHOOL
        c.rect(DX - 70, 252, DX + 70, 286, rgb("#f6f0e0"), INK, 2)
        try:
            from PIL import ImageFont
            fnt = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 24 * 4)
            c.d.text((DX * 4, 270 * 4), "SCHOOL", fill=rgb("#2f5fd8"), font=fnt, anchor="mm")
        except Exception:
            pass
        # the door: a porch, the double door, glass panes, the warm hall when open
        x0, x1, ys, yb = DOOR
        c.rect(x0 - 14, ys - 18, x1 + 14, yb, TRIM)
        c.rect(x0 - 20, ys - 26, x1 + 20, ys - 14, rgb("#2f5fd8"))
        if door > 0:
            c.rect(x0, ys, x1, yb, mix(WARM, 0.15 * flick))
            c.glow(DX, yb - 60, 50, WARM, 150)
            for kk in range(3):                       # coat hooks with little coats
                hx = x0 + 14 + kk * 26
                c.line([(hx, ys + 22), (hx, ys + 30)], INK, 2)
                c.poly([(hx - 7, ys + 30), (hx + 7, ys + 30), (hx + 9, ys + 60), (hx - 9, ys + 60)], LANT[(kk * 3) % 7])
        else:
            c.rect(x0, ys, x1, yb, rgb("#2f5fd8"))
        if door < 1:
            w = (x1 - x0) / 2
            for side in (-1, 1):
                hx = x0 if side < 0 else x1
                lw = w * math.cos(door * math.pi / 2)
                ex = hx - side * lw
                xa, xb = min(hx, ex), max(hx, ex)
                c.rect(xa, ys, xb, yb, dark(rgb("#2f5fd8"), 0.3 * door))
                if lw > 10:
                    c.rect(xa + 6, ys + 12, xb - 6, ys + 70, mix(GLASS, 0.3), INK, 1.2)
                    c.ell(ex + side * 7, (ys + yb) / 2 + 12, 3, 3, rgb("#e2b340"), INK, 1)
        c.rect(x0 - 30, yb, x1 + 30, GROUND, rgb("#cfc6b4"), INK, 1.4)
        return c.out()

    fl = [0.5 + 0.5 * math.sin(2 * math.pi * k / 4) for k in range(4)]
    write_anim("school", {
        "idle": ([frame(flick=f) for f in fl], 3, True),
        "open": ([frame(door=k / 6) for k in range(7)], 10, False),
        "opened": ([frame(door=1, flick=f) for f in fl], 3, True),
    }, {"unit_px": UNIT_PX, "origin_px": [DX, GROUND], "door_px": [DX, DOOR[3]], "baked_by": "tools/bake/school.py"})


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "building"
    if cmd == "building":
        building()
    elif cmd == "recipes":
        write_recipes()
    elif cmd == "bake":
        sys.exit(0 if bake(sys.argv[2:] or list(TEACHERS)) else 1)
