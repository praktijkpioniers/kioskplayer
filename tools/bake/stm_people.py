def person(doc, body, hide=(), recolor=None, props=(), clips=None, parts=(), bone_scale=None, mesh_scale=None):
    r = {"_doc": f"St Maarten {doc}; generated by tools/bake/stm_people.py - edit there",
         "model": G + body + ".glb", "hide": GEAR + list(hide), "outline": 0.01, "props_rest": True,
         "frame": FRAME, "recolor": recolor or {}, "props": list(props), "clips": clips}
    if parts:
        r["parts"] = [{"model": G + m + ".glb", "meshes": [mesh]} for m, mesh in parts]
    if bone_scale:
        r["bone_scale"] = bone_scale
    if mesh_scale:
        r["mesh_scale"] = mesh_scale
    return r


